SELECT /*+ FULL(r) */
    r.RECOMMENDATION_ID,
    r.OFFER_ID,
    r.SEGMENT_CODE,
    r.ELIGIBILITY_SCORE,
    r.EXCLUSION_FLAG
FROM STAGE_OWNER.TBL_RECOMMEND_MAIN r
WHERE r.PROCESSING_STATUS = 'READY'
  AND r.BUSINESS_DATE = TO_DATE('${BATCH_DATE}', 'YYYY-MM-DD')
